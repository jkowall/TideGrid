describe("encodeQr", () => {
  it("matches a reference encoder for a short text", () => {
    const code = encodeQr("hi", { mask: 2 });
    expect(code.version).toBe(1);
    expect(text(code)).toEqual(HI_MASK_2);
  });

  it("matches a reference encoder for a signing link, at the smallest version that holds it", () => {
    const code = encodeQr(URL, { mask: 4 });
    expect(code.version).toBe(6);
    expect(code.size).toBe(41);
    expect(text(code)).toEqual(URL_MASK_4);
  });

  it("chooses a mask by itself and holds up to version 10", () => {
    const code = encodeQr(URL);
    expect(code.mask).toBeGreaterThanOrEqual(0);
    expect(code.mask).toBeLessThan(8);
    expect(capacity(10)).toBe(213);
    expect(encodeQr("y".repeat(213)).version).toBe(10);
    expect(() => encodeQr("y".repeat(214))).toThrow(RangeError);
  });

  it("draws the dark modules inside a quiet zone", () => {
    const path = qrPath(encodeQr("hi", { mask: 2 }));
    expect(path.startsWith("M4 4h1v1h-1z")).toBe(true);
    expect(path.split("z").length - 1).toBe(HI_MASK_2.join("").split("#").length - 1);
  });
});
