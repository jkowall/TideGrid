export type FakePaymentControlResponse = z.infer<typeof FakePaymentControlResponse>;

// Staff reads ------------------------------------------------------------------------

export const StaffBooking = z.object({
  id: Uuid,
  reference: z.string(),
  tripId: Uuid,
  partySize: z.number().int().min(1),
  state: z.literal("confirmed"),
  source: z.literal("direct"),
  reacquired: z
    .boolean()
    .describe("Confirmed after its hold had expired, by taking the seats again"),
  confirmedAt: Instant,
  booker: z.object({ name: z.string(), email: z.string() }),
  order: z.object({
    id: Uuid,
    status: z.enum(["pending", "paid", "void"]),
    total: Cents,
    currency: z.literal("USD"),
  }),
  payment: z.object({
    id: Uuid,
    provider: PaymentProviderName,
    state: z.enum(["pending", "succeeded", "failed"]),
    amount: Cents,
  }),
});
export type StaffBooking = z.infer<typeof StaffBooking>;

export const TripBookingsResponse = z
  .object({ bookings: z.array(StaffBooking) })
  .describe("Every booking on the trip, oldest first");
export type TripBookingsResponse = z.infer<typeof TripBookingsResponse>;

export const FinalizationReason = z
  .enum([
    "no_capacity",
    "trip_canceled",
    "trip_unavailable",
    "sales_closed",
    "party_size_out_of_range",
    "session_failed",
    "session_canceled",
    "payment_mismatch",
  ])
  .describe(
    "Why a verified payment could not become a booking. payment_mismatch is not refunded automatically; investigate it at the provider",
  );

export const FinalizationException = z.object({
  id: Uuid,
  reason: FinalizationReason,
  checkoutSessionId: Uuid,
  tripId: Uuid,
  paymentId: Uuid,
  amount: Cents,
  createdAt: Instant,
  refund: z
    .object({
      id: Uuid,
      state: RefundState,
      amount: Cents,
      failureCode: z.string().nullable(),
      settledAt: Instant.nullable(),
    })
    .nullable(),
});
export type FinalizationException = z.infer<typeof FinalizationException>;

export const FinalizationExceptionQuery = z.object({
  limit: z.coerce.number().int().min(1).max(100).default(50),
});

export const FinalizationExceptionsResponse = z
  .object({ exceptions: z.array(FinalizationException) })
  .describe("Payments that could not become bookings, newest first, for operator follow-up");
export type FinalizationExceptionsResponse = z.infer<typeof FinalizationExceptionsResponse>;
